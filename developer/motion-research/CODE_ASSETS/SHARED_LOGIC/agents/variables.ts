/**
 * Sanitizes a variable ID by only taking the last part of the ID if separated by dots
 *
 * @param id The ID that may contain a scope prefix
 * @returns The ID that is the last part of the ID if separated by dots
 */
export function sanitizeVariableId(id: string): string {
  const splitId = id.split('.')

  if (splitId.length === 1) {
    return id
  }

  return splitId.slice(-1)[0]
}
